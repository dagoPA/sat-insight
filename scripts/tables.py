def products(book: dict) -> None:
    labels = {
        "built_surface": "GHSL built-up surface",
        "built_height": "GHSL building height",
        "population": "GHSL population",
        "nightlights": "Nighttime lights",
    }
    frames = {
        (tag, split): read(
            suffixed(f"data/global_products{'_test' if split == 'test' else ''}.csv", tag)
        )
        for tag, _ in BACKBONES
        for split in ("val", "test")
    }
    aurocs = []
    for tag, name in BACKBONES:
        v, t = frames[(tag, "val")], frames[(tag, "test")]
        aurocs.append(
            f"{fmt(v.ours_auc_high.iloc[0] if v is not None else None)} on validation and {fmt(t.ours_auc_high.iloc[0] if t is not None else None)} on test with {name}"
        )
    rows = []
    for product, label in labels.items():
        for split in ("val", "test"):
            first = frames[(BACKBONES[0][0], split)]
            cells = [label if split == "val" else "", split]
            if first is None:
                cells.append(DASH)
            else:
                p = first.set_index("product").loc[product]
                cells.append(
                    ci(p.proxy_within, p.proxy_ci_low, p.proxy_ci_high)
                    .replace("[-", "[$-$")
                    .replace(", -", ", $-$")
                )
            for tag, _ in BACKBONES:
                f = frames[(tag, split)]
                if f is None:
                    cells += [DASH, DASH]
                    continue
                p = f.set_index("product").loc[product]
                cells += [
                    ci(p.ours_within, p.ours_ci_low, p.ours_ci_high),
                    signed(p.difference, p.ci_low, p.ci_high),
                ]
            cells.append(
                fmt(first.set_index("product").loc[product].proxy_auc_high)
                if first is not None
                else DASH
            )
            rows.append(" & ".join(cells) + "\\\\")
    header = f" & & & \\multicolumn{{2}}{{c}}{{{BACKBONES[0][1]}}} & \\multicolumn{{2}}{{c}}{{{BACKBONES[1][1]}}} & \\\\\n\\cmidrule(lr){{4-5}}\\cmidrule(lr){{6-7}}\nProduct & Split & Product $\\rho$ [95\\%] & Map $\\rho$ [95\\%] & $\\Delta$ [95\\%] & Map $\\rho$ [95\\%] & $\\Delta$ [95\\%] & AUROC product"
    table(
        "products",
        "Free global products under the map's own protocol, for both feature extractors. "
        "Within-$\\rho$ is the mean over municipalities of the within-municipality Spearman "
        "correlation against the held-out tract grade on the identical universe (22 municipalities "
        "per split), each with its 95\\% percentile bootstrap over cities; $\\Delta$ is the paired "
        "difference, map minus product, on the same city draws. AUROC is pooled detection of high "
        f"and very-high grade tracts across the split (map: {aurocs[0]}, {aurocs[1]}). Orientation "
        "was fixed before measurement: deprivation is the negative of every product. The "
        "nighttime-light row rests on interior-point sampling for 63\\% of tracts, which are "
        "smaller than one of its 30 arcsec cells.",
        "llcccccc",
        header,
        rows,
        label="tab:products",
        resize=True,
    )


