"""Writes the manuscript's result tables as LaTeX from the canon and the result files.

Every table that carries a measured number is generated here and pulled into main.tex
with \\input, so a rerun of the protocol regenerates the tables the way it regenerates the
figures, and a number in a table can never disagree with the canon. The captions live
here too, because several of them quote numbers. Both feature extractors of
`satinsight.manuscript.BACKBONES` are reported side by side; a cell whose artifact does
not exist yet is written as a dash, so the tables can be built while a run is in flight.

Usage: tables.py [destination directory]
"""

import sys
import warnings
from pathlib import Path

warnings.filterwarnings("ignore")

import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

from satinsight.manuscript import BACKBONES, CV_NAMES, canon, suffixed  # noqa: E402

OUT = Path(sys.argv[1] if len(sys.argv) > 1 else "docs/manuscript/tables")
DASH = "--"


def thousands(n) -> str:
    return f"{int(n):,}".replace(",", "{,}")


def fmt(value, digits: int = 3) -> str:
    return (
        DASH
        if value is None or (isinstance(value, float) and np.isnan(value))
        else f"{value:.{digits}f}"
    )


def ci(value, low, high, digits: int = 3) -> str:
    if value is None:
        return DASH
    return f"{value:.{digits}f} [{low:.{digits}f}, {high:.{digits}f}]"


def signed(value, low, high, digits: int = 3) -> str:
    return f"${value:+.{digits}f}$ [${low:+.{digits}f}$, ${high:+.{digits}f}$]"


def read(path: str) -> pd.DataFrame | None:
    return pd.read_csv(path) if Path(path).exists() else None


def table(
    name: str,
    caption: str,
    spec: str,
    header: str,
    rows: list[str],
    *,
    label: str,
    small: bool = True,
    resize: bool = False,
) -> None:
    body = "\n".join(rows)
    tabular = f"\\begin{{tabular}}{{{spec}}}\n\\toprule\n{header}\\\\\n\\midrule\n{body}\n\\bottomrule\n\\end{{tabular}}"
    if resize:
        tabular = f"\\resizebox{{\\linewidth}}{{!}}{{%\n{tabular}}}"
    text = (
        "% generated by scripts/tables.py; edit the script, not this file\n"
        "\\begin{table}[htbp]\n\\centering\n"
        f"\\caption{{{caption}}}\n"
        + ("\\small\n" if small else "")
        + tabular
        + f"\n\\label{{{label}}}\n\\end{{table}}\n"
    )
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / f"{name}.tex").write_text(text)


