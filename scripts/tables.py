        "is assigned by the isotonic score-to-grade map fitted on the validation tracts. $\\kappa$ "
        "is quadratic-weighted Cohen's kappa and accuracy is over the five grades, both pooled over "
        "the split's tracts; AUROC is the mean over the four cumulative thresholds (grade at least "
        "$k$), pooled over the split and averaged over the 22 municipalities with at least twenty "
        "tracts.",
